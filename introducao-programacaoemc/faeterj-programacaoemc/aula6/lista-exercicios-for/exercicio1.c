/**
 * Crie uma lista iniciando em 0 e que conte ate 10
 * Utilizando a estrutura de repetição for
 */

 #include <stdio.h>
 #include <stdlib.h>

 int main(int argc, char const *argv[])
 {

    printf("************************* \n");
    printf("*      EXERCICIO 1      * \n");
    printf("*   INICIO DA CONTAGEM  * \n");

    for (int i = 0; i <=10; i++) {
        printf("%d\n", i);
    }

    printf("*      FIM DA CONTAGEM      * \n");
    system("pause");
    return 0;
 }
 